<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Routing\Route as RouteInstance;
use Illuminate\Routing\Router;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;
use ReflectionClass;
use ReflectionMethod;
use ReflectionNamedType;

/**
 * `php artisan api:docs` — OpenAPI 3.1 from the route table.
 *
 * Generated rather than hand-written, and the reason is
 * [`docs/03-api-specification.md`](../../../../docs/03-api-specification.md)
 * itself: that document is the *contract*, written before the code, and it has
 * already drifted from the routes twice — four endpoints in its admin table had
 * no routes at all until this phase. A spec file maintained by hand drifts; one
 * generated from `Route::getRoutes()` cannot, because the route table is what
 * actually serves traffic.
 *
 * What it reads, in order of reliability:
 *
 *   • the route table — method, URI, name, middleware. Ground truth.
 *   • the controller's FormRequest, via reflection on the action's signature.
 *     `rules()` is instantiated and read, which turns Laravel validation into a
 *     requestBody schema. This is the part that pays for the command.
 *   • the controller docblock, for the summary.
 *
 * What it does NOT do: infer response schemas. A Resource's `toArray()` is
 * conditional on `whenLoaded` and `when`, and the gated-fields rule means the
 * shape genuinely differs per caller — a generated response schema would be
 * confidently wrong, which is worse than absent. Responses carry the envelope
 * and the documented status codes; the field-level payloads stay in the spec
 * document, which is hand-written *prose* about intent rather than a
 * machine-readable duplicate of the code.
 */
class GenerateApiDocs extends Command
{
    // The default output path is not arbitrary: `web/website/package.json` and
    // `web/admin/package.json` both already run
    // `openapi-typescript ../backend/storage/api/openapi.json`, so writing
    // anywhere else means `npm run generate:api` silently reads a stale file or
    // none at all.
    protected $signature = 'api:docs
                            {--output=storage/api/openapi.json : Where to write the document}
                            {--prefix=api/v1 : Only document routes under this URI prefix}
                            {--pretty : Indent the JSON for reading and diffing}';

    protected $description = 'Generate an OpenAPI 3.1 document from the registered API routes';

    public function handle(Router $router): int
    {
        $prefix = trim((string) $this->option('prefix'), '/');

        $routes = collect($router->getRoutes())
            ->filter(fn (RouteInstance $route) => Str::startsWith($route->uri(), $prefix))
            // A route registered for GET is also registered for HEAD, and
            // documenting both doubles the file for no reader.
            ->filter(fn (RouteInstance $route) => $route->methods() !== ['HEAD'])
            ->sortBy(fn (RouteInstance $route) => $route->uri())
            ->values();

        if ($routes->isEmpty()) {
            $this->components->error("No routes matched the prefix [{$prefix}].");

            return self::FAILURE;
        }

        $document = [
            'openapi' => '3.1.0',
            'info' => [
                'title' => config('app.name').' API',
                'version' => 'v1',
                'description' => 'Generated by `php artisan api:docs` from the route table. '
                    .'Do not edit by hand — regenerate it.',
            ],
            'servers' => [['url' => rtrim((string) config('app.url'), '/')]],
            'components' => $this->components(),
            'security' => [['sanctum' => []]],
            'tags' => $this->tags($routes),
            'paths' => $this->paths($routes),
        ];

        $path = base_path((string) $this->option('output'));

        File::ensureDirectoryExists(dirname($path));

        File::put($path, json_encode(
            $document,
            JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
                | ($this->option('pretty') ? JSON_PRETTY_PRINT : 0),
        ));

        $this->components->info(sprintf(
            'Documented %d endpoints across %d paths → %s',
            $routes->count(),
            count($document['paths']),
            $path,
        ));

        return self::SUCCESS;
    }

    // --- Document sections -------------------------------------------------

    /**
     * Tags come from the second URI segment after the version — `interests`,
     * `admin`, `cms`. Grouping by controller would be more precise and much
     * less useful: `CmsManagementController` serves four resources, and nobody
     * reading the docs is looking for a class name.
     *
     * @param  Collection<int, RouteInstance>  $routes
     * @return array<int, array<string, string>>
     */
    protected function tags($routes): array
    {
        return $routes
            ->map(fn (RouteInstance $route) => $this->tagFor($route))
            ->unique()
            ->sort()
            ->values()
            ->map(fn (string $tag) => ['name' => $tag])
            ->all();
    }

    /**
     * @param  Collection<int, RouteInstance>  $routes
     * @return array<string, mixed>
     */
    protected function paths($routes): array
    {
        $paths = [];

        foreach ($routes as $route) {
            // Laravel writes `{user}`; OpenAPI writes `{user}` too, so only the
            // leading slash and any optional-parameter `?` need normalising.
            $uri = '/'.str_replace('?}', '}', $route->uri());

            foreach ($route->methods() as $method) {
                if ($method === 'HEAD') {
                    continue;
                }

                $paths[$uri][strtolower($method)] = $this->operation($route, $method);
            }
        }

        return $paths;
    }

    /** @return array<string, mixed> */
    protected function operation(RouteInstance $route, string $method): array
    {
        $authenticated = $this->isAuthenticated($route);

        $operation = [
            'tags' => [$this->tagFor($route)],
            'summary' => $this->summaryFor($route),
            'operationId' => $route->getName() ?: strtolower($method).'-'.Str::slug($route->uri()),
            'parameters' => $this->parameters($route),
            'responses' => $this->responses($route, $method, $authenticated),
        ];

        // An empty `security` array is how OpenAPI says "this one is public",
        // and it has to be explicit — omitting the key inherits the document's
        // global requirement, which would mark every public CMS route as
        // needing a token.
        if (! $authenticated) {
            $operation['security'] = [];
        }

        if ($body = $this->requestBody($route)) {
            $operation['requestBody'] = $body;
        }

        if ($throttle = $this->throttleFor($route)) {
            $operation['description'] = "Rate limited: {$throttle}.";
        }

        return $operation;
    }

    /**
     * Path parameters, from the URI rather than from a docblock — the URI is
     * the only place they cannot be wrong.
     *
     * All typed as `string`. Most are integer ids, but `{profile_code}` is not,
     * `{slug}` is not, and `{action}` is an enum; declaring integer would be
     * wrong for a third of them, and reading the `where()` constraints back off
     * the route to tell them apart is more machinery than the accuracy is worth.
     *
     * @return array<int, array<string, mixed>>
     */
    protected function parameters(RouteInstance $route): array
    {
        return collect($route->parameterNames())
            ->map(function (string $name) use ($route) {
                $pattern = $route->wheres[$name] ?? null;

                return array_filter([
                    'name' => $name,
                    'in' => 'path',
                    'required' => true,
                    'schema' => array_filter([
                        'type' => 'string',
                        // A `where()` on the route is a real constraint the
                        // caller has to satisfy, so it travels as a pattern.
                        'pattern' => $pattern,
                    ]),
                ]);
            })
            ->all();
    }

    /**
     * The body, derived from the FormRequest in the controller's signature.
     *
     * This is where the command earns its place: the validation rules are the
     * actual contract — a `min:20` on the contact form, an `in:` list on an
     * action — and they are already written. Reflecting them out means the docs
     * cannot disagree with what the endpoint accepts.
     *
     * `rules()` is called on a bare instance. Nearly all of them are pure
     * arrays; a few reference `$this->route(...)` for conditional rules, and
     * those throw on an unbooted request — hence the catch. A rule set that
     * cannot be read statically is simply omitted rather than guessed at.
     *
     * @return array<string, mixed>|null
     */
    protected function requestBody(RouteInstance $route): ?array
    {
        if (! $rules = $this->rulesFor($route)) {
            return null;
        }

        $properties = [];
        $required = [];

        foreach ($rules as $field => $rule) {
            $tokens = $this->tokenise($rule);

            // Dot and star notation — `audience.gender`, `photo_ids.*`. Flatten
            // to the parent as a loose array/object rather than building nested
            // schemas: three levels of `whenLoaded` in the Resources means the
            // detail would not be trustworthy anyway.
            if (str_contains((string) $field, '.')) {
                continue;
            }

            $properties[$field] = $this->schemaFor($tokens);

            if (in_array('required', $tokens, true)) {
                $required[] = $field;
            }
        }

        if ($properties === []) {
            return null;
        }

        return [
            'required' => $required !== [],
            'content' => [
                'application/json' => [
                    'schema' => array_filter([
                        'type' => 'object',
                        'properties' => $properties,
                        'required' => $required ?: null,
                    ]),
                ],
            ],
        ];
    }

    /**
     * Laravel validation rules → a JSON Schema fragment.
     *
     * Deliberately shallow. It covers the rules this codebase actually uses in
     * volume — types, `in:`, `min`/`max`, `nullable` — and leaves the rest as an
     * untyped property. A more thorough translation would be a rule engine, and
     * it would still not know that `exists:users,id` means "a member, not
     * staff".
     *
     * @param  array<int, string>  $tokens
     * @return array<string, mixed>
     */
    protected function schemaFor(array $tokens): array
    {
        $type = match (true) {
            in_array('integer', $tokens, true) => 'integer',
            in_array('numeric', $tokens, true) => 'number',
            in_array('boolean', $tokens, true) => 'boolean',
            in_array('array', $tokens, true) => 'array',
            in_array('file', $tokens, true), in_array('image', $tokens, true) => 'string',
            default => 'string',
        };

        $schema = ['type' => $type];

        if (in_array('nullable', $tokens, true)) {
            // OpenAPI 3.1 drops the 3.0 `nullable` keyword in favour of a type
            // union, which is why this document declares 3.1.0.
            $schema['type'] = [$type, 'null'];
        }

        foreach ($tokens as $token) {
            [$name, $argument] = array_pad(explode(':', $token, 2), 2, null);

            $format = match ($name) {
                'email' => 'email',
                'url' => 'uri',
                'date' => 'date',
                'date_format' => 'date-time',
                'file', 'image' => 'binary',
                default => null,
            };

            if ($format !== null) {
                $schema['format'] = $format;
            }

            if ($name === 'in' && $argument !== null) {
                $schema['enum'] = str_getcsv($argument);
            }

            // On a string `min`/`max` are lengths; on a number they are bounds.
            // Same rule name, different keyword, and getting it backwards makes
            // the document actively misleading rather than merely thin.
            if (in_array($name, ['min', 'max'], true) && $argument !== null) {
                $keyword = match (true) {
                    $name === 'min' && $type === 'string' => 'minLength',
                    $name === 'min' => 'minimum',
                    $type === 'string' => 'maxLength',
                    default => 'maximum',
                };

                $schema[$keyword] = (int) $argument;
            }
        }

        return $schema;
    }

    /**
     * Status codes every endpoint in this API can return, plus the ones this
     * particular route's middleware and rules imply.
     *
     * Hand-listed against the envelope rather than inferred from the
     * controller. `bootstrap/app.php` maps exceptions to these shapes
     * centrally, so this list is accurate for every route by construction —
     * which is exactly the payoff of having one envelope.
     *
     * @return array<string, mixed>
     */
    protected function responses(RouteInstance $route, string $method, bool $authenticated): array
    {
        $success = match ($method) {
            'POST' => '201',
            'DELETE' => '204',
            default => '200',
        };

        $responses = [
            $success => [
                'description' => 'Success',
                'content' => ['application/json' => ['schema' => ['$ref' => '#/components/schemas/Envelope']]],
            ],
        ];

        if ($this->rulesFor($route)) {
            $responses['422'] = ['$ref' => '#/components/responses/ValidationError'];
        }

        if ($authenticated) {
            $responses['401'] = ['$ref' => '#/components/responses/Unauthenticated'];
            $responses['403'] = ['$ref' => '#/components/responses/Forbidden'];
        }

        if ($route->parameterNames() !== []) {
            $responses['404'] = ['$ref' => '#/components/responses/NotFound'];
        }

        if ($this->throttleFor($route)) {
            $responses['429'] = ['$ref' => '#/components/responses/TooManyRequests'];
        }

        return $responses;
    }

    /**
     * The reusable halves of the document — the envelope, and the four error
     * responses `bootstrap/app.php` produces.
     *
     * @return array<string, mixed>
     */
    protected function components(): array
    {
        $error = [
            'type' => 'object',
            'properties' => [
                'success' => ['type' => 'boolean', 'const' => false],
                'message' => ['type' => 'string'],
                'errors' => ['type' => ['object', 'null']],
            ],
        ];

        $response = fn (string $description) => [
            'description' => $description,
            'content' => ['application/json' => ['schema' => ['$ref' => '#/components/schemas/Error']]],
        ];

        return [
            'securitySchemes' => [
                'sanctum' => [
                    'type' => 'http',
                    'scheme' => 'bearer',
                    'description' => 'A Sanctum personal access token. Staff tokens carry the `admin` ability.',
                ],
            ],

            'schemas' => [
                // `data` is intentionally untyped — see the class docblock. The
                // envelope is guaranteed; what sits inside it is documented in
                // prose, because the gated-fields rule makes the shape depend
                // on the caller's plan and on the target's privacy settings.
                'Envelope' => [
                    'type' => 'object',
                    'required' => ['success', 'message'],
                    'properties' => [
                        'success' => ['type' => 'boolean', 'const' => true],
                        'message' => ['type' => 'string'],
                        'data' => true,
                        'meta' => [
                            'type' => 'object',
                            'description' => 'Present on paginated and keyset collections only.',
                            'properties' => [
                                'current_page' => ['type' => 'integer'],
                                'per_page' => ['type' => 'integer'],
                                'total' => ['type' => 'integer'],
                                'last_page' => ['type' => 'integer'],
                                'next_cursor' => ['type' => ['integer', 'null']],
                                'has_more' => ['type' => 'boolean'],
                            ],
                        ],
                    ],
                ],
                'Error' => $error,
            ],

            'responses' => [
                'ValidationError' => $response('Validation failed. `errors` is keyed by field.'),
                'Unauthenticated' => $response('Missing, expired or revoked token.'),
                'Forbidden' => $response('Authenticated but not permitted. Also the paywall: `errors.upgrade_required` is true and `errors.suggested_plans` lists the plans that unlock the feature.'),
                'NotFound' => $response('Not found — or hidden from this viewer. The two are deliberately indistinguishable.'),
                'TooManyRequests' => $response('Throttled.'),
            ],
        ];
    }

    // --- Reflection --------------------------------------------------------

    /**
     * The FormRequest rules for a route's action, or null.
     *
     * Memoised per route because `responses()` and `requestBody()` both ask,
     * and answering means instantiating a class.
     *
     * @return array<string, mixed>|null
     */
    protected function rulesFor(RouteInstance $route): ?array
    {
        static $cache = [];

        $key = $route->uri().'|'.implode(',', $route->methods());

        if (array_key_exists($key, $cache)) {
            return $cache[$key];
        }

        return $cache[$key] = $this->resolveRules($route);
    }

    /** @return array<string, mixed>|null */
    protected function resolveRules(RouteInstance $route): ?array
    {
        if (! $method = $this->actionReflection($route)) {
            return null;
        }

        foreach ($method->getParameters() as $parameter) {
            $type = $parameter->getType();

            if (! $type instanceof ReflectionNamedType || $type->isBuiltin()) {
                continue;
            }

            $class = $type->getName();

            if (! is_subclass_of($class, FormRequest::class)) {
                continue;
            }

            try {
                $rules = (new $class)->rules();

                return is_array($rules) ? $rules : null;
            } catch (\Throwable $e) {
                // A conditional rule set that reads the route or the
                // authenticated user. Omitted, not guessed — see the docblock
                // on requestBody().
                $this->components->warn("Could not read rules from {$class}: {$e->getMessage()}");

                return null;
            }
        }

        return null;
    }

    /**
     * The first line of the controller method's docblock, falling back to the
     * class's, falling back to a sentence built from the verb and the URI.
     *
     * A generated summary from the URI is genuinely useful here because this
     * codebase names its routes after what they do — but a real docblock is
     * always better, and most of these controllers have one.
     */
    protected function summaryFor(RouteInstance $route): string
    {
        $reflection = $this->actionReflection($route);

        foreach ([$reflection, $reflection?->getDeclaringClass()] as $subject) {
            if ($summary = $this->firstDocLine($subject)) {
                return $summary;
            }
        }

        return Str::headline(str_replace('/', ' ', (string) $route->getActionMethod()));
    }

    /** @param  ReflectionMethod|ReflectionClass|null  $subject */
    protected function firstDocLine($subject): ?string
    {
        $doc = $subject?->getDocComment();

        if (! $doc) {
            return null;
        }

        foreach (preg_split('/\R/', $doc) ?: [] as $line) {
            $line = trim(preg_replace('/^\s*\/?\*+\/?/', '', $line) ?? '');

            // Skip the blank lead-in and any annotation; take the first line of
            // actual prose. Truncated because a summary is a tooltip and some
            // of these docblocks open with a full paragraph.
            if ($line !== '' && ! Str::startsWith($line, ['@', '|', '/'])) {
                return Str::limit($line, 120);
            }
        }

        return null;
    }

    protected function actionReflection(RouteInstance $route): ?ReflectionMethod
    {
        $action = $route->getAction('uses');

        if (! is_string($action) || ! str_contains($action, '@')) {
            // A closure route, or an invokable resolved without the method.
            // Neither appears in this API's route files today.
            return null;
        }

        [$class, $method] = explode('@', $action, 2);

        try {
            return (new ReflectionClass($class))->getMethod($method);
        } catch (\ReflectionException) {
            return null;
        }
    }

    // --- Route reading -----------------------------------------------------

    protected function tagFor(RouteInstance $route): string
    {
        // `api/v1/admin/users` → `admin`; `api/v1/interests/sent` → `interests`.
        $segments = explode('/', $route->uri());

        return $segments[2] ?? 'general';
    }

    protected function isAuthenticated(RouteInstance $route): bool
    {
        return collect($route->gatherMiddleware())
            ->contains(fn ($m) => is_string($m) && Str::startsWith($m, 'auth:'));
    }

    protected function throttleFor(RouteInstance $route): ?string
    {
        return collect($route->gatherMiddleware())
            ->first(fn ($m) => is_string($m) && Str::startsWith($m, 'throttle:'));
    }

    /**
     * A rule value can be a pipe string, an array, or an array containing rule
     * *objects* (`Rule::requiredIf(...)`, `Password::min(8)`). Objects are
     * stringified where they support it and dropped where they do not.
     *
     * @return array<int, string>
     */
    protected function tokenise(mixed $rule): array
    {
        $tokens = is_string($rule) ? explode('|', $rule) : (array) $rule;

        return collect($tokens)
            ->map(function ($token) {
                if (is_string($token)) {
                    return $token;
                }

                // `Rule::requiredIf` stringifies to 'required' or '' depending
                // on the condition it was built with — which for a conditional
                // rule means the generated doc reflects the unbooted case. That
                // is stated in the requestBody() docblock rather than hidden.
                return is_object($token) && method_exists($token, '__toString')
                    ? (string) $token
                    : null;
            })
            ->filter(fn ($token) => is_string($token) && $token !== '')
            ->values()
            ->all();
    }
}
